package doom.codegen.defs;

import doom.codegen.defs.OriginalDefs.CheatRow;
import doom.codegen.defs.OriginalDefs.MiscRow;
import doom.codegen.defs.OriginalDefs.SoundRow;
import doom.codegen.defs.OriginalDefs.StateRow;
import doom.codegen.defs.OriginalDefs.StringEntry;
import doom.codegen.defs.OriginalDefs.ThingRow;
import doom.codegen.defs.OriginalDefs.WeaponRow;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes the committed snapshot of the original tables (test resource {@code original-defs.txt}). One record per
 * line, fields separated by tabs; text fields escape backslash, tab, newline and carriage return.
 */
final class SnapshotWriter {

    private final OriginalDefs d;

    SnapshotWriter(OriginalDefs defs) {
        this.d = defs;
    }

    void write(Path file) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("# Snapshot of the original definition tables (linuxdoom-1.10 info.c, sounds.c, d_items.c, p_inter.c;\n");
        sb.append("# Chocolate Doom 3.1.1 d_englsh.h, deh_*.c). Generated by `doom-codegen gen-defs`; do not edit.\n");
        for (int i = 0; i < d.spriteNames().size(); i++) {
            line(sb, "sprite", i, d.spriteNames().get(i));
        }
        for (StateRow s : d.states()) {
            line(sb, "state", s.index(), s.name(), s.sprite(), s.frame(), s.tics(),
                    s.action() == null ? "NONE" : s.action(), s.next(), s.misc1(), s.misc2());
        }
        for (ThingRow t : d.things()) {
            Object[] f = new Object[2 + t.values().size()];
            f[0] = t.index();
            f[1] = t.name();
            for (int i = 0; i < t.values().size(); i++) {
                f[2 + i] = t.values().get(i);
            }
            line(sb, "thing", f);
        }
        for (WeaponRow w : d.weapons()) {
            Object[] f = new Object[1 + w.values().size()];
            f[0] = w.index();
            for (int i = 0; i < w.values().size(); i++) {
                f[1 + i] = w.values().get(i);
            }
            line(sb, "weapon", f);
        }
        for (int i = 0; i < d.maxAmmo().length; i++) {
            line(sb, "ammo", i, d.maxAmmo()[i], d.clipAmmo()[i]);
        }
        for (SoundRow s : d.sounds()) {
            line(sb, "sfx", s.index(), s.name(), s.singularity() ? 1 : 0, s.priority(), s.link(), s.pitch(), s.volume());
        }
        for (int i = 0; i < d.musicNames().size(); i++) {
            line(sb, "music", i, d.musicNames().get(i) == null ? "-" : d.musicNames().get(i));
        }
        for (StringEntry e : d.strings()) {
            line(sb, "string", e.key(), e.bex() ? 1 : 0, escape(e.text()));
        }
        for (CheatRow c : d.cheats()) {
            line(sb, "cheat", c.index(), c.dehName(), c.variable(), c.parameterChars(), escape(c.sequence()));
        }
        for (MiscRow m : d.misc()) {
            line(sb, "misc", m.dehName(), m.variable(), m.defaultValue());
        }
        Files.createDirectories(file.getParent());
        Files.writeString(file, sb.toString(), StandardCharsets.UTF_8);
    }

    private static void line(StringBuilder sb, String kind, Object... fields) {
        sb.append(kind);
        for (Object f : fields) {
            sb.append('\t').append(f);
        }
        sb.append('\n');
    }

    static String escape(String s) {
        StringBuilder sb = new StringBuilder();
        for (char c : s.toCharArray()) {
            switch (c) {
                case '\\' -> sb.append("\\\\");
                case '\t' -> sb.append("\\t");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                default -> sb.append(c);
            }
        }
        return sb.toString();
    }
}
